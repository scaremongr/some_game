import assert from 'node:assert/strict';
import {resolve} from 'node:path';
import {createArena} from '../server/index.mjs';
process.env.PLAYWRIGHT_BROWSERS_PATH ||= resolve('.browsers');
const {chromium}=await import('playwright');
const app=await createArena({dev:true});app.server.listen(0,'127.0.0.1');await new Promise(r=>app.server.once('listening',r));
const browser=await chromium.launch({headless:true,args:['--enable-unsafe-swiftshader']});
const p=await browser.newPage({viewport:{width:1280,height:800}});const errors=[];
p.on('pageerror',e=>errors.push(e.message));
await p.route('https://telegram.org/**',r=>r.fulfill({body:''}));
const state=()=>p.evaluate(()=>JSON.parse(new TextDecoder().decode(window.arenaRenderBytes)));
const wait=fn=>p.waitForFunction(fn,{},{timeout:7000});
try {
  await p.goto(`http://127.0.0.1:${app.server.address().port}`);
  await p.waitForSelector('#loader',{state:'hidden',timeout:45000});
  await p.click('#practice');await p.click('#training-mode');
  await wait(()=>JSON.parse(new TextDecoder().decode(window.arenaRenderBytes)).phase===1);
  await p.screenshot({path:'artifacts/room-intact.png'});
  await p.keyboard.down('d');
  await wait(()=>{const s=JSON.parse(new TextDecoder().decode(window.arenaRenderBytes));return s.fighters[1].x-s.fighters[0].x<850;});
  await p.keyboard.up('d');await p.keyboard.press('j');
  await wait(()=>JSON.parse(new TextDecoder().decode(window.arenaRenderBytes)).fighters[0].combo===1);
  await p.keyboard.press('j');
  await wait(()=>JSON.parse(new TextDecoder().decode(window.arenaRenderBytes)).fighters[0].combo===2);
  await p.keyboard.press('u');
  await wait(()=>JSON.parse(new TextDecoder().decode(window.arenaRenderBytes)).fighters[0].combo===3);
  assert.ok((await state()).fighters[0].combo_damage<34);
  await p.screenshot({path:'artifacts/combo-roundhouse.png'});
  await p.waitForTimeout(1200);
  // The approach can stop outside smash range of the intact coffee table at -500 mm.
  await p.keyboard.down('a');
  await wait(()=>JSON.parse(new TextDecoder().decode(window.arenaRenderBytes)).fighters[0].x<0);
  await p.keyboard.up('a');
  const before=await state();
  assert.ok(before.objects[7].hp>0,'The coffee table must be intact before the smash');
  assert.ok(Math.abs(before.fighters[0].x+500)<=950,'The coffee table must be in smash range');
  await p.click('#room-damage');await p.waitForTimeout(1200);
  assert.equal((await state()).objects[7].hp,0,'The smash must destroy the coffee table');
  await p.screenshot({path:'artifacts/room-destroyed.png'});
  await p.keyboard.press('w');
  await wait(()=>JSON.parse(new TextDecoder().decode(window.arenaRenderBytes)).fighters[0].y>500);
  await p.keyboard.press('u');await p.waitForTimeout(100);
  assert.equal((await state()).fighters[0].action,13);
  await p.screenshot({path:'artifacts/jump-kick.png'});
  await p.setViewportSize({width:390,height:844});await p.waitForTimeout(700);
  await p.screenshot({path:'artifacts/room-mobile.png'});
  assert.deepEqual(errors,[]);
  console.log('Combat browser PASS: real J-J-U confirmed string, scaled damage, room smash, jump kick, desktop/mobile room.');
} finally {await browser.close();await app.close();}
